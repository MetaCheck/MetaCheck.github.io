let currentLang = 'ja';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N['ja'][key] || key;
}

function catName(cat) {
  if (!cat) return '';
  return (CAT_NAMES[currentLang] && CAT_NAMES[currentLang][cat.trim()]) || CAT_NAMES['ja'][cat.trim()] || cat;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = currentLang === 'cn' ? 'zh' : currentLang;
}

function changeLanguage(lang) {
  currentLang = lang;
  applyI18n();
  document.querySelectorAll('.lang-pill, .lang-switcher__option').forEach(function(btn) {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  document.querySelectorAll('.lang-switcher__btn').forEach(function(btn) {
    btn.textContent = lang.toUpperCase();
  });
  localStorage.setItem('lang', lang);

  // 表示中の患者・クリニック画面を再描画
  if (window._patientScores) {
    renderPatientScores(window._patientScores);
  }
}

