let currentLang = 'ja';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N['ja'][key] || key;
}

function catName(cat) {
  if (!cat) return '';
  return (CAT_NAMES[currentLang] && CAT_NAMES[currentLang][cat.trim()]) || CAT_NAMES['ja'][cat.trim()] || cat;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = currentLang === 'cn' ? 'zh' : currentLang;
}

function changeLanguage(lang) {
  currentLang = lang;
  applyI18n();
  document.querySelectorAll('.lang-pill, .lang-switcher__option, .lang-opt').forEach(function(btn) {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  document.querySelectorAll('.lang-switcher__btn, #lang-btn-patient, #lang-btn-clinic').forEach(function(btn) {
    btn.textContent = lang.toUpperCase();
  });
  localStorage.setItem('lang', lang);

  // ダウンロードボタンのテキスト更新
  var dlBtnTexts = { ja:'アプリをダウンロード', en:'Download App', vi:'Tải ứng dụng', cn:'下载应用' };
  var dlBtn = document.getElementById('pwa-dl-btn-text');
  if (dlBtn) dlBtn.textContent = dlBtnTexts[lang] || dlBtnTexts.ja;

  // 患者画面を再描画
  if (window._patientScores && typeof renderPatientScores === 'function') {
    renderPatientScores(window._patientScores);
  }
  // 患者カテゴリ詳細を再描画
  if (window._currentPatientIndex != null && typeof selectPatientScore === 'function') {
    selectPatientScore(window._currentPatientIndex, document.querySelector('.pt-score-row.active'));
  }
  // クリニック画面を再描画
  if (window._clinicPatientId && typeof selectClinicPatient === 'function') {
    selectClinicPatient(window._clinicPatientId);
  }
  // クリニックカテゴリ詳細を再描画
  if (window._clinicCurrentCat && typeof selectClinicCat === 'function') {
    var c = window._clinicCurrentCat;
    selectClinicCat(c.cardEl, c.patientId, c.category);
  }
}

document.addEventListener('DOMContentLoaded', function() {
  var saved = localStorage.getItem('lang') || 'ja';
  changeLanguage(saved);
});

